export function norm(s) {
  return String(s || '').replace(/['׳"״]/g, '').replace(/\s+/g, ' ').trim();
}

function wordMatches(word, kw) {
  // Also try the word without a leading ל/ה/ו/ב/מ/ש ("למדיח" → "מדיח").
  const forms = [word];
  if (word.length > 3 && 'להובמש'.includes(word[0])) forms.push(word.slice(1));
  return forms.some(f => f === kw || (kw.length >= 3 && f.startsWith(kw)));
}

export function guessCategory(name) {
  const text = norm(name);
  if (!text) return null;
  for (const [cat, kws] of RULES) {
    for (const kw of kws) if (kw.includes(' ') && text.includes(norm(kw))) return cat;
  }
  // The first word usually names the product ("אורז לבן", "חומץ יין"); then the rest.
  for (const word of text.split(' ')) {
    for (const [cat, kws] of RULES) {
      for (const kw of kws) if (!kw.includes(' ') && wordMatches(word, norm(kw))) return cat;
    }
  }
  return null;
}

// Receipt lines that are not products.
export function isNonProduct(name) {
  const t = norm(name);
  return /פיקדון|שקיות ידני|^שקית/.test(t);
}
